export const DICTIONARIES: Record<string, Dict> = {
  en,
  'en-US': en,
  'pt-BR': ptBR,
  pt: ptBR,
  es,
  'es-ES': es,
  'de-DE': deDE,
  de: deDE,
  'fr-FR': frFR,
  fr: frFR,
  'it-IT': itIT,
  it: itIT,
  'ja-JP': jaJP,
  ja: jaJP,
  'zh-CN': zhCN,
  zh: zhCN,
};

export type Translate = (key: string, vars?: Record<string, string>) => string;

export function makeTranslator(lang: string): Translate {
  const normalized = DICTIONARIES[lang]
    ? lang
    : lang?.startsWith('de')
    ? 'de-DE'
    : lang?.startsWith('fr')
    ? 'fr-FR'
    : lang?.startsWith('it')
    ? 'it-IT'
    : lang?.startsWith('pt')
    ? 'pt-BR'
    : lang?.startsWith('es')
    ? 'es-ES'
    : lang?.startsWith('ja')
    ? 'ja-JP'
    : lang?.startsWith('zh')
    ? 'zh-CN'
    : 'en-US';
  const dict = DICTIONARIES[normalized] ?? DICTIONARIES[lang] ?? en;
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
}

